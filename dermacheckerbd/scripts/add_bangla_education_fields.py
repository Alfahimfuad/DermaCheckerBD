def patch_file(path: Path) -> None:
    text = path.read_text(encoding='utf-8')

    # Patch each entry one at a time. We re-scan the text after every
    # insertion so the indices reflect the new file state — otherwise
    # earlier insertions shift later offsets and entries get skipped.
    # Idempotent: only inserts fields that are missing from each entry.
    for code, fields in BANGLA_FIELDS.items():
        entry_marker = f'    "{code}": {{'
        idx = text.find(entry_marker)
        if idx == -1:
            print(f"  ! Could not locate entry for code '{code}'")
            continue

        # Skip if this entry already has all five new fields.
        if f'"bangla_overview"' in text[idx:idx + 5000]:
            print(f"  Already has bangla_overview: {code}")
            continue

        bangla_summary_idx = text.find('"bangla_summary"', idx, idx + 6000)
        if bangla_summary_idx == -1:
            print(f"  ! Could not find bangla_summary in entry '{code}'")
            continue

        line_start = text.rfind('\n', 0, bangla_summary_idx) + 1
        indent = text[line_start:bangla_summary_idx]

        new_lines = []
        for key in (
            'bangla_overview',
            'bangla_appearance',
            'bangla_symptoms',
            'bangla_care',
            'bangla_when_to_see_doctor',
        ):
            value = fields[key]
            new_lines.append(f'{indent}"{key}": (')
            words = value.split(' ')
            line = ''
            for w in words:
                if len(line) + len(w) + 1 > 70:
                    new_lines.append(f'{indent * 2}"{line} "')
                    line = w
                else:
                    line = f'{line} {w}'.strip()
            if line:
                new_lines.append(f'{indent * 2}"{line}"')
            new_lines.append(f'{indent}),')
        new_lines.append('')

        insert_text = '\n'.join(new_lines) + '\n'
        text = text[:line_start] + insert_text + text[line_start:]
        print(f"  Patched entry: {code}")

    path.write_text(text, encoding='utf-8')
    print(f"  Wrote: {path}")


if __name__ == '__main__':
    base = Path(__file__).resolve().parent.parent
    target = base / 'apps' / 'education' / 'content.py'
    print(f"Patching {target} ...")
    patch_file(target)
    print("Done.")
